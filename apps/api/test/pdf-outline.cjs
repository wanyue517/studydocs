const { strict: assert } = require('node:assert');
const { mkdtempSync, rmSync, readFileSync } = require('node:fs');
const { tmpdir } = require('node:os');
const { join } = require('node:path');
const dir = mkdtempSync(join(tmpdir(), 'studydocs-pdf-ai-'));
process.env.STORAGE_DIR = dir;
process.env.ADMIN_USERNAME = 'studyadmin'; process.env.ADMIN_PASSWORD = 'InitialPassword123!';
const { DatabaseService } = require('../dist/database.service');
const { SiteService } = require('../dist/site.service');
const { StorageService } = require('../dist/storage.service');
const { AuthService } = require('../dist/auth');
const { DocumentsService } = require('../dist/documents.service');
const { AiService } = require('../dist/ai.service');
const { PdfOutlineService } = require('../dist/pdf-outline.service');
const tick = () => new Promise(resolve => setImmediate(resolve));
(async () => {
  const database = new DatabaseService(); const originalFetch = global.fetch;
  try {
    const site = new SiteService(database), storage = new StorageService(database), auth = new AuthService(database, site);
    const docs = new DocumentsService(database, storage, site); docs.onModuleInit();
    const ai = new AiService(database), outlines = new PdfOutlineService(database, docs, ai);
    const owner = database.db.prepare("SELECT id FROM users WHERE role='admin'").get().id;
    site.patch({ allowRegistration: true });
    const member = auth.register('newmember', 'Password1234!');
    const pdf = await docs.upload(owner, { originalname: 'test.pdf', buffer: Buffer.from('%PDF-1.4\ntest'), size: 13 }, null);
    assert.throws(() => outlines.get(member.id, pdf.id), /不存在/);
    assert.throws(() => outlines.get(owner, docs.create(owner, { name: 'note', kind: 'markdown' }).id), /仅 PDF/);
    const input = { name: 'Test AI', provider: 'compatible', baseUrl: 'https://example.com/v1', model: 'test', apiKey: 'private-test-key' };
    const profile = ai.save(input);
    assert.equal('apiKey' in profile, false); assert.equal(profile.hasKey, true);
    const cipher = database.db.prepare('SELECT secret FROM ai_profiles WHERE id=?').get(profile.id).secret;
    assert.ok(!cipher.includes(input.apiKey));
    assert.equal(readFileSync(join(dir, 'ai-secret.key')).length, 32);
    ai.save({ ...input, apiKey: '' }, profile.id);
    assert.equal(ai.connection(profile.id).apiKey, input.apiKey);
    assert.throws(() => ai.save({ ...input, provider: 'openai', apiKey: '' }, profile.id), /重新填写/);
    assert.throws(() => ai.save({ ...input, baseUrl: 'https://user:secret@example.com' }), /格式无效/);
    ai.activate(profile.id);
    let calls = 0; let modelResponse = 'valid';
    global.fetch = async (url, init) => {
      calls++;
      assert.equal(url, 'https://example.com/v1/chat/completions');
      assert.equal(init.headers.Authorization, 'Bearer private-test-key');
      const body = JSON.parse(init.body); assert.equal(body.model, 'test');
      if (modelResponse === 'http-error') return new Response('SECRET PROVIDER ERROR', { status: 401 });
      const data = JSON.parse(body.messages[1].content);
      const entries = data.pages.slice(0, 2).map((p, index) => ({ title: `Heading ${p.page}`, page: p.page, level: index ? 2 : 1 }));
      const content = modelResponse === 'valid' ? '```json\n' + JSON.stringify({ entries }) + '\n```' : '{"entries":[{"title":"bad","level":1,"page":999}]}';
      return Response.json({ choices: [{ message: { content }, finish_reason: 'stop' }] });
    };
    const pages = Array.from({ length: 25 }, (_, index) => ({ page: index + 1, text: `Chapter ${index + 1}` }));
    const started = outlines.start(owner, pdf.id, { pages, pageCount: 25 });
    assert.equal(started.job.status, 'running');
    assert.throws(() => outlines.start(owner, pdf.id, { pages, pageCount: 25 }), /已有/);
    for (let n = 0; n < 100 && outlines.get(owner, pdf.id).job.status === 'running'; n++) await tick();
    const generated = outlines.get(owner, pdf.id);
    assert.equal(generated.job.status, 'completed'); assert.equal(calls, 5);
    assert.deepEqual(generated.entries.map(e => e.page), [1,2,6,7,11,12,16,17,21,22]);
    const another = new PdfOutlineService(database, docs, ai);
    assert.deepEqual(another.get(owner, pdf.id).entries, generated.entries, '目录跨服务实例持久化');
    // A repeated request must reuse all successful batches without spending tokens.
    outlines.start(owner, pdf.id, { pages, pageCount: 25 });
    for (let n = 0; n < 100 && outlines.get(owner, pdf.id).job.status === 'running'; n++) await tick();
    assert.equal(calls, 5);
    modelResponse = 'invalid';
    pages[0].text += ' changed';
    outlines.start(owner, pdf.id, { pages, pageCount: 25 });
    for (let n = 0; n < 100 && outlines.get(owner, pdf.id).job.status === 'running'; n++) await tick();
    assert.equal(outlines.get(owner, pdf.id).job.status, 'failed');
    assert.deepEqual(outlines.get(owner, pdf.id).entries, generated.entries, '失败保留旧目录');
    modelResponse = 'valid';
    const beforeResume = calls;
    outlines.resume(owner, pdf.id);
    for (let n = 0; n < 100 && outlines.get(owner, pdf.id).job.status === 'running'; n++) await tick();
    assert.equal(outlines.get(owner, pdf.id).job.status, 'completed');
    assert.equal(calls - beforeResume, 1, '只请求修改后失败的批次，其他批次复用');
    generated.updatedAt = outlines.get(owner, pdf.id).updatedAt;
    // Fail after one committed batch, then reconstruct the service and resume.
    pages[0].text += ' revision'; pages[5].text += ' revision';
    const realChat = ai.chat.bind(ai); let attempted = 0;
    ai.chat = async (...args) => { if (++attempted === 2) throw new Error('simulated timeout'); return realChat(...args); };
    outlines.start(owner, pdf.id, { pages, pageCount: 25 });
    for (let n = 0; n < 100 && outlines.get(owner, pdf.id).job.status === 'running'; n++) await tick();
    assert.equal(outlines.get(owner, pdf.id).job.status, 'failed');
    assert.equal(outlines.get(owner, pdf.id).job.progress, 20);
    assert.equal(outlines.get(owner, pdf.id).partialEntries.length, 2);
    assert.throws(() => outlines.resume(member.id, pdf.id), /不存在/);
    ai.chat = realChat;
    const restored = new PdfOutlineService(database, docs, ai);
    const beforeRecovery = calls;
    restored.resume(owner, pdf.id);
    for (let n = 0; n < 100 && restored.get(owner, pdf.id).job.status === 'running'; n++) await tick();
    assert.equal(restored.get(owner, pdf.id).job.status, 'completed');
    assert.equal(calls - beforeRecovery, 1, '重启后跳过成功批次，仅重试失败批次');
    generated.updatedAt = restored.get(owner, pdf.id).updatedAt;
    assert.throws(() => outlines.save(owner, pdf.id, { entries: [], pageCount: 25, updatedAt: 'stale' }), /其他窗口/);
    const edited = outlines.save(owner, pdf.id, { entries: [{ title: 'Corrected', level: 1, page: 4 }], pageCount: 25, updatedAt: generated.updatedAt });
    assert.equal(edited.entries[0].page, 4); assert.equal(edited.job, null);
    assert.throws(() => outlines.save(owner, pdf.id, { entries: [{ title: 'bad', level: 0, page: 26 }], pageCount: 25, updatedAt: edited.updatedAt }), /无效/);
    assert.throws(() => outlines.start(owner, pdf.id, { pages: [{ page: 1, text: '' }], pageCount: 1 }), /OCR/);
    modelResponse = 'http-error';
    await assert.rejects(() => ai.chat(ai.connection(), 'test', 'test'), error => /API Key 无效/.test(error.message) && !error.message.includes('SECRET'));
    docs.trash(owner, pdf.id); await docs.removeForever(owner, pdf.id);
    assert.equal(database.db.prepare('SELECT COUNT(*) n FROM pdf_outlines').get().n, 0);
    console.log('✓ PDF AI: 加密配置 / 密钥保留 / 分批生成 / 页码验证 / 用户隔离 / 失败保留 / 目录持久化 / 编辑冲突 / 扫描件 / 删除清理');
  } finally { global.fetch = originalFetch; database.onModuleDestroy(); rmSync(dir, { recursive: true, force: true }); }
})().catch(error => { console.error(error); process.exitCode = 1; });
